/**
 * Trigger download of plain text review report
 */
export function exportReviewAsText(reviewResult, patientInfo = {}) {
  const lines = [];
  lines.push("================================================================================");
  lines.push("MEDIGUARD AI - MEDICATION SAFETY CLINICAL REVIEW REPORT");
  lines.push("HACKATHON PROTOTYPE ONLY - NOT FOR MEDICAL OR REAL PRESCRIBING USE");
  lines.push("Talent AP Mega Hackathon 2026 | Problem Statement H4: Medication Safety");
  lines.push("MediGuard AI Clinical Decision Support | Inpatient Medication Safety");
  lines.push("================================================================================");
  lines.push(`Generated: ${new Date().toLocaleString()}`);
  lines.push(`Session Integrity Stamp: DEMO-${Math.random().toString(36).substring(2, 9).toUpperCase()}`);
  lines.push("");

  lines.push("--- CLINICAL CONTEXT ---");
  lines.push(`Synthetic Patient ID: ${patientInfo.id || patientInfo.patientId || "SYN-DEMO-RECORD"}`);
  lines.push(`Patient Name:        ${patientInfo.name || patientInfo.patientName || "Synthetic Patient"}`);
  lines.push(`Age:                 ${reviewResult.clinicalContext?.age || patientInfo.age || "N/A"} years`);
  lines.push(`Weight:              ${reviewResult.clinicalContext?.weight || patientInfo.weightKg || "N/A"} kg`);
  lines.push(`eGFR:                ${reviewResult.clinicalContext?.eGfr || patientInfo.eGfr || "N/A"} mL/min/1.73m²`);
  lines.push(`Pregnancy Status:    ${reviewResult.clinicalContext?.pregnancyStatus || patientInfo.pregnancyStatus || "N/A"}`);
  lines.push(`Diagnoses:           ${(reviewResult.clinicalContext?.diagnoses || patientInfo.diagnoses || []).join(", ") || "None recorded"}`);
  lines.push("");

  lines.push("--- EVALUATED MEDICATIONS ---");
  (reviewResult.resolvedMedications || []).forEach((m, idx) => {
    lines.push(`[${idx + 1}] ${m.rawInput} -> Mapped Generic: ${m.resolvedGeneric} (${m.drugClass}) | RxNorm: ${m.rxNormId}`);
    lines.push(`    Strength: ${m.strength || "N/A"} | Dose: ${m.dose || "N/A"} | Route: ${m.route || "Oral"} | Frequency: ${m.frequency || "Daily"}`);
    lines.push(`    Mapping Confidence: ${m.confidence}% (${m.matchType})`);
  });
  lines.push("");

  lines.push("--- SAFETY ALERTS SUMMARY ---");
  lines.push(`Total Alerts: ${reviewResult.totalAlerts}`);
  lines.push(`Critical: ${reviewResult.severityCounts.Critical} | High: ${reviewResult.severityCounts.High} | Moderate: ${reviewResult.severityCounts.Moderate} | Low: ${reviewResult.severityCounts.Low}`);
  lines.push("");

  if (reviewResult.alerts && reviewResult.alerts.length > 0) {
    reviewResult.alerts.forEach((alert, idx) => {
      lines.push(`>>> ALERT #${idx + 1}: [${alert.severity.toUpperCase()}] ${alert.title}`);
      lines.push(`    Category:         ${alert.category}`);
      lines.push(`    Matched Rule ID:  ${alert.matchedRule || alert.ruleCode}`);
      lines.push(`    Involved Drugs:   ${(alert.involvedMedicines || []).join(" + ")}`);
      lines.push(`    Why Flagged:      ${alert.whyFlagged}`);
      lines.push(`    Evidence Level:   ${alert.evidence}`);
      lines.push(`    Certainty:        ${alert.confidence}`);
      lines.push(`    Limitations:      ${alert.limitations}`);
      lines.push(`    Prescriber Action:${alert.suggestedAction}`);
      lines.push("");
    });
  } else {
    lines.push(">>> No issues detected in the available demo rules.");
    lines.push("    Note: An incomplete medication list or limited catalogue cannot establish absolute patient safety.");
    lines.push("");
  }

  lines.push("================================================================================");
  lines.push("DISCLAIMER: This report is generated by an illustrative hackathon prototype.");
  lines.push("It does NOT constitute real clinical advice or replace qualified human judgment.");
  lines.push("================================================================================");

  const blob = new Blob([lines.join("\n")], { type: "text/plain;charset=utf-8" });
  downloadBlob(blob, `MediGuard_Review_${patientInfo.id || "Report"}_${Date.now()}.txt`);
}

/**
 * Trigger download of CSV report for alerts
 */
export function exportReviewAsCSV(reviewResult, patientInfo = {}) {
  const headers = [
    "Alert_ID",
    "Severity",
    "Category",
    "Title",
    "Involved_Medicines",
    "Matched_Rule",
    "Confidence",
    "Why_Flagged",
    "Suggested_Action",
    "Limitations"
  ];

  const rows = [];
  if (reviewResult.alerts && reviewResult.alerts.length > 0) {
    reviewResult.alerts.forEach(a => {
      rows.push([
        escapeCsv(a.id),
        escapeCsv(a.severity),
        escapeCsv(a.category),
        escapeCsv(a.title),
        escapeCsv((a.involvedMedicines || []).join(" + ")),
        escapeCsv(a.matchedRule || a.ruleCode),
        escapeCsv(a.confidence),
        escapeCsv(a.whyFlagged),
        escapeCsv(a.suggestedAction),
        escapeCsv(a.limitations)
      ]);
    });
  } else {
    rows.push([
      "NONE",
      "INFO",
      "Clear",
      "No issue detected in the available demo rules",
      "None",
      "N/A",
      "100%",
      "No matching rule in illustrative catalogue",
      "Perform standard clinical review",
      "Demo rule engine is illustrative"
    ]);
  }

  const csvContent = [
    headers.join(","),
    ...rows.map(r => r.join(","))
  ].join("\n");

  const blob = new Blob([csvContent], { type: "text/csv;charset=utf-8" });
  downloadBlob(blob, `MediGuard_Alerts_${patientInfo.id || "Report"}_${Date.now()}.csv`);
}

/**
 * Helper to escape CSV fields
 */
function escapeCsv(str) {
  if (str === null || str === undefined) return '""';
  const s = String(str).replace(/"/g, '""');
  return `"${s}"`;
}

/**
 * Helper to trigger browser file download
 */
function downloadBlob(blob, filename) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

/**
 * Print clean hospital report
 */
export function printReviewReport() {
  window.print();
}
